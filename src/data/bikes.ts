export function getBikeById(id: string): BikeModel | undefined {
  return bikes.find((b) => b.id === id);
}

export function getBrands(): string[] {
  return [...new Set(bikes.map((b) => b.brand))].sort();
}

export function getModelsByBrand(brand: string): string[] {
  return [...new Set(bikes.filter((b) => b.brand === brand).map((b) => b.model))].sort();
}

export function getYearsByBrandModel(brand: string, model: string): number[] {
  return [...new Set(
    bikes.filter((b) => b.brand === brand && b.model === model).map((b) => b.year)
  )].sort((a, z) => z - a);
}

export function getBikeByBrandModelYear(brand: string, model: string, year: number): BikeModel | undefined {
  return bikes.find((b) => b.brand === brand && b.model === model && b.year === year);
}
